"""Run the real model on every client, score the labelled cases and report measured cost.

    uv run python -m evals.run                   # evals only
    uv run python -m evals.run --snapshot FILE   # also write the signals snapshot migration

Not part of the test suite: it costs money and a model's output can change between runs.
"""

import argparse
import json
from pathlib import Path

from sqlalchemy import create_engine

from app import repository
from app.config import get_settings
from app.domain.signals import Signals
from app.llm.extractor import PROMPT_VERSION, OpenAIExtractor
from app.services.signals import client_sources, source_hash, verify
from evals.cases import CASES

# USD per million tokens (input, output), from OpenAI's model pages, November 2026
PRICES = {"gpt-5.4-mini": (0.75, 4.50), "gpt-4.1-mini": (0.40, 1.60)}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--snapshot", type=Path)
    args = parser.parse_args()

    settings = get_settings()
    if not settings.openai_api_key:
        raise SystemExit("OPENAI_API_KEY is not set")
    engine = create_engine(settings.database_url)
    with engine.connect() as conn:
        reference = repository.load_reference(conn)
        feedback = {cid: repository.client_feedback(conn, cid) for cid in reference.clients}
    extractor = OpenAIExtractor(settings.openai_api_key, settings.openai_model, reference.markets)

    results: dict[str, tuple[Signals, list[str], str, str, int, int]] = {}
    for client_id in reference.clients:
        sources = client_sources(reference, client_id, feedback[client_id])
        extraction = extractor.extract(sources)
        signals, dropped = verify(extraction.signals, sources, reference, feedback[client_id])
        results[client_id] = (
            signals,
            dropped,
            source_hash(sources, extractor.model),
            extraction.model,
            extraction.input_tokens,
            extraction.output_tokens,
        )
        print(f"{client_id}: {extraction.input_tokens} in / {extraction.output_tokens} out")
        for reason in dropped:
            print(f"    dropped {reason}")

    passed = 0
    print()
    for case in CASES:
        ok = case.check(results[case.client_id][0], reference.clients[case.client_id].client)
        passed += ok
        print(f"{'PASS' if ok else 'FAIL'}  {case.client_id} {case.name}: {case.expected}")
        if not ok:
            print(f"      got: {results[case.client_id][0].model_dump_json(exclude_none=True)}")
    print(f"\n{passed}/{len(CASES)} cases pass")

    tokens_in = sum(r[4] for r in results.values())
    tokens_out = sum(r[5] for r in results.values())
    price = PRICES.get(settings.openai_model)
    print(f"Tokens: {tokens_in} in, {tokens_out} out for {len(results)} clients")
    if price:
        cost = (tokens_in * price[0] + tokens_out * price[1]) / 1_000_000
        print(f"Cost: ${cost:.4f} in total, ${cost / len(results):.5f} per client")

    if args.snapshot:
        args.snapshot.write_text(snapshot_sql(results))
        print(f"Wrote {args.snapshot}")


def snapshot_sql(results: dict[str, tuple[Signals, list[str], str, str, int, int]]) -> str:
    rows = []
    for client_id, (signals, dropped, digest, model, tokens_in, tokens_out) in results.items():
        values = [
            client_id,
            signals.model_dump_json(),
            json.dumps(dropped),
            digest,
            model,
            PROMPT_VERSION,
        ]
        quoted = ", ".join("'" + v.replace("'", "''") + "'" for v in values)
        rows.append(f"  ({quoted}, {tokens_in}, {tokens_out})")
    return (
        "-- Generated by `python -m evals.run --snapshot`: signals the real model extracted\n"
        "-- from the provided data, so the app shows them without an API key. An upsert, so a\n"
        "-- newer snapshot replaces an older one in a new migration.\n"
        "INSERT INTO client_signals (client_id, signals, dropped, source_hash, model, "
        "prompt_version, input_tokens, output_tokens) VALUES\n" + ",\n".join(rows) + "\n"
        "ON CONFLICT (client_id) DO UPDATE SET signals = EXCLUDED.signals, "
        "dropped = EXCLUDED.dropped, source_hash = EXCLUDED.source_hash, model = EXCLUDED.model, "
        "prompt_version = EXCLUDED.prompt_version, input_tokens = EXCLUDED.input_tokens, "
        "output_tokens = EXCLUDED.output_tokens, extracted_at = now();\n"
    )


if __name__ == "__main__":
    main()
